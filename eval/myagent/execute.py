"""Generation driver for a custom agent.

Builds one instance per question, runs your agent (agent.run_agent) over them in
parallel with resume support, and writes each prediction to
    <output_dir>/<id>/predicted_0.sql   (+ generation.log)
which unify.py then reshapes into the unified generated/ + gold/ layout.

You normally do NOT edit this file — put your agent in agent.py.
"""
import os
import argparse
import traceback
from concurrent.futures import ThreadPoolExecutor

from tqdm import tqdm

from prompt import build_instances
from utils import EvalConfig
from agent import run_agent


def _output_paths(output_dir, instance_id):
    instance_dir = os.path.join(output_dir, instance_id)
    return instance_dir, os.path.join(instance_dir, "predicted_0.sql"), os.path.join(instance_dir, "generation.log")


def _process(instance, model, output_dir):
    instance_id = instance["id"]
    instance_dir, sql_file, log_file = _output_paths(output_dir, instance_id)
    try:
        sql = run_agent(instance, model) or ""
        log = f"Question:\n{instance['question']}\n\nGenerated SQL:\n{sql}"
    except Exception as e:
        sql = ""
        log = f"Error: {e}\n{traceback.format_exc()}"
        print(f"Error on {instance_id}: {e}")

    # Writes are inside their own guard so a single failed write (bad locale,
    # disk full, permissions) fails just this instance instead of aborting the
    # whole batch via fut.result().
    try:
        os.makedirs(instance_dir, exist_ok=True)
        with open(sql_file, "w", encoding="utf-8") as f:
            f.write(sql)
        with open(log_file, "w", encoding="utf-8") as f:
            f.write(log)
    except Exception as e:
        print(f"Failed to write output for {instance_id}: {e}")
        return instance_id, False
    return instance_id, bool(sql)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", type=str, default="codex")
    parser.add_argument("--dataset", type=str, default="dw")
    parser.add_argument("--q_fn", type=str, default="dev_sampled")
    parser.add_argument("--output_dir", type=str, required=True)
    parser.add_argument("--data_dir", type=str, default="../../data")
    parser.add_argument("--num_workers", type=int, default=4)
    # --setting flags (set by run.sh)
    parser.add_argument("--gold_tables", action="store_true")
    parser.add_argument("--join_keys", action="store_true")
    parser.add_argument("--mapping", action="store_true")
    parser.add_argument("--knowledge", action="store_true")
    parser.add_argument("--decomp", action="store_true")
    args = parser.parse_args()

    eval_config = EvalConfig(
        gold_tables=args.gold_tables, join_keys=args.join_keys,
        mapping=args.mapping, knowledge=args.knowledge, decomp=args.decomp,
    )
    print(eval_config)

    instances = build_instances(args.dataset, args.q_fn, eval_config, args.data_dir)
    os.makedirs(args.output_dir, exist_ok=True)

    # Resume: skip instances that already have a non-empty prediction.
    todo = []
    for inst in instances:
        _, sql_file, _ = _output_paths(args.output_dir, inst["id"])
        if not os.path.exists(sql_file) or os.path.getsize(sql_file) == 0:
            todo.append(inst)

    print(f"Output directory: {args.output_dir}")
    if not todo:
        print("All instances already processed.")
        return
    print(f"Running agent on {len(todo)} / {len(instances)} instances (model={args.model})...")

    with ThreadPoolExecutor(max_workers=args.num_workers) as ex:
        futures = [ex.submit(_process, inst, args.model, args.output_dir) for inst in todo]
        for fut in tqdm(futures, total=len(futures)):
            fut.result()


if __name__ == "__main__":
    main()
